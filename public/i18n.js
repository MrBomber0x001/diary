  const arabic = Object.fromEntries(Object.entries(english).map(([source, translated]) => [translated, source]));
  const translatedAttributes = ['placeholder', 'title', 'aria-label'];
  const originalText = new WeakMap();
  const pendingText = new WeakMap();
  const originalAttributes = new WeakMap();
  const pendingAttributes = new WeakMap();
  let language = 'ar';

  function translateTextNode(node, fromObserver = false) {
    if (fromObserver && pendingText.has(node)) {
      const expected = pendingText.get(node);
      pendingText.delete(node);
      if (node.nodeValue === expected) return;
    }
    if (!node.nodeValue.trim()) return;
    if (!originalText.has(node)) {
      const current = node.nodeValue.trim();
      originalText.set(node, english[current] ? current : arabic[current] || current);
    } else if (fromObserver) {
      const current = node.nodeValue.trim();
      const knownOriginal = originalText.get(node);
      if (current !== english[knownOriginal] && current !== knownOriginal) {
        originalText.set(node, english[current] ? current : arabic[current] || current);
      }
    }
    const original = originalText.get(node);
    const currentValue = node.nodeValue;
    const leading = original.match(/^\s*/)[0];
    const trailing = currentValue.match(/\s*$/)[0];
    const translated = language === 'en' ? english[original] || original : original;
    const nextValue = `${leading}${translated}${trailing}`;
    if (nextValue !== currentValue) {
      pendingText.set(node, nextValue);
      node.nodeValue = nextValue;
    }
  }

  function translateAttribute(element, attribute, fromObserver = false) {
    let originals = originalAttributes.get(element);
    if (!originals) {
      originals = new Map();
      originalAttributes.set(element, originals);
    }
    let pending = pendingAttributes.get(element);
    if (!pending) {
      pending = new Map();
      pendingAttributes.set(element, pending);
    }
    const current = element.getAttribute(attribute);
    if (fromObserver && pending.has(attribute)) {
      const expected = pending.get(attribute);
      pending.delete(attribute);
      if (current === expected) return;
    }
    if (current === null) return;
    if (!originals.has(attribute)) {
      originals.set(attribute, english[current] ? current : arabic[current] || current);
    } else if (fromObserver) {
      const knownOriginal = originals.get(attribute);
      if (current !== english[knownOriginal] && current !== knownOriginal) {
        originals.set(attribute, english[current] ? current : arabic[current] || current);
      }
    }
    const original = originals.get(attribute);
    const translated = language === 'en' ? english[original] || original : original;
    if (translated !== current) {
      pending.set(attribute, translated);
      element.setAttribute(attribute, translated);
    }
  }

  function translateElement(element, fromObserver = false) {
    if (element.nodeType === Node.TEXT_NODE) {
      if (element.parentElement?.closest('[dir="auto"], textarea, input, .markdown-preview, [data-user-content]')) return;
      translateTextNode(element, fromObserver);
      return;
    }
    if (element.nodeType !== Node.ELEMENT_NODE) return;
    const preserveContent = element.matches('[dir="auto"], textarea, input, .markdown-preview, [data-user-content]');
    translatedAttributes.forEach(attribute => {
      translateAttribute(element, attribute, fromObserver);
    });
    if (preserveContent) return;
    element.childNodes.forEach(child => translateElement(child, fromObserver));
  }

  function setLanguage(nextLanguage) {
    language = nextLanguage === 'en' ? 'en' : 'ar';
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.dataset.language = language;
    translateElement(document.head);
    translateElement(document.body);
  }

  const observer = new MutationObserver(records => {
    records.forEach(record => {
      if (record.type === 'childList') record.addedNodes.forEach(node => translateElement(node, true));
      else if (record.type === 'characterData') translateTextNode(record.target, true);
      else if (record.type === 'attributes') translateAttribute(record.target, record.attributeName, true);
    });
  });
  observer.observe(document.documentElement, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: translatedAttributes,
  });
  window.personalMemoLanguage = { set: setLanguage, get: () => language };
